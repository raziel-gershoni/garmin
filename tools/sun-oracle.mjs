// Writes common/test/SunFixtures.mc: sunrise/sunset from @hebcal/core's NOAA zmanim
// (elevation 0) for a few places and dates, to check SunTimes.noaa() within a tolerance.
//
//   cd tools && node sun-oracle.mjs
import { Zmanim, GeoLocation } from '@hebcal/core';
import { writeFileSync } from 'node:fs';

const places = [
  ['Jerusalem', 31.778, 35.235, 'Asia/Jerusalem'],
  ['Tel Aviv', 32.0853, 34.7818, 'Asia/Jerusalem'],
  ['New York', 40.7128, -74.006, 'America/New_York'],
  ['Melbourne', -37.8136, 144.9631, 'Australia/Melbourne'],
];
const dates = ['2026-01-15', '2026-03-20', '2026-06-21', '2026-10-19', '2026-12-21', '2027-04-02'];

const localParts = (d, tz) => {
  const p = Object.fromEntries(new Intl.DateTimeFormat('en-GB', {
    timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit', timeZoneName: 'longOffset',
  }).formatToParts(d).map(x => [x.type, x.value]));
  const m = /GMT([+-])(\d\d):(\d\d)/.exec(p.timeZoneName);
  const offset = m ? (m[1] === '-' ? -1 : 1) * (Number(m[2]) * 3600 + Number(m[3]) * 60) : 0;
  return { secs: Number(p.hour) * 3600 + Number(p.minute) * 60 + Number(p.second), offset };
};
const rdOf = (y, m, d) => {
  const py = y - 1;
  let rd = 365 * py + Math.floor(py / 4) - Math.floor(py / 100) + Math.floor(py / 400) + Math.floor((367 * m - 362) / 12) + d;
  if (m > 2) rd -= (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 1 : 2;
  return rd;
};

const rows = [];
for (const [name, lat, lon, tz] of places) {
  for (const iso of dates) {
    const [y, m, d] = iso.split('-').map(Number);
    const z = new Zmanim(new GeoLocation(name, lat, lon, 0, tz), new Date(y, m - 1, d, 12), false);
    const rise = localParts(z.sunrise(), tz), set = localParts(z.sunset(), tz);
    rows.push(`        /* ${name} ${iso} */ [${rdOf(y, m, d)}, ${lat}d, ${lon}d, ${rise.offset}, ${rise.secs}, ${set.secs}]`);
  }
}

writeFileSync(new URL('../common/test/SunFixtures.mc', import.meta.url), `import Toybox.Lang;

// Generated by tools/sun-oracle.mjs from @hebcal/core Zmanim — do not edit.
(:test)
module SunFixtures {
    // [rd, lat, lon, utcOffsetSec, sunriseSec, sunsetSec]
    const ROWS = [
${rows.join(',\n')}
    ];
}
`);
console.log(`wrote ${rows.length} sun fixtures`);
