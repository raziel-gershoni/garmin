// Writes face/test/TitleFixtures.mc: every parasha title (Israel schedule) and every holiday
// that replaces one on Shabbat, over 20 years, as Hebcal renders them in Hebrew. The layout
// test checks that each one fits the parasha line.
//
//   cd tools && node titles-oracle.mjs
import { HebrewCalendar, flags } from '@hebcal/core';
import { writeFileSync } from 'node:fs';

const events = HebrewCalendar.calendar({
  start: new Date(2026, 0, 1), end: new Date(2046, 0, 1), sedrot: true, il: true,
  noMinorFast: true, noModern: true, noRoshChodesh: true, noSpecialShabbat: true,
});
const byDate = new Map();
for (const ev of events) {
  const key = ev.getDate().greg().toDateString();
  if (!byDate.has(key)) byDate.set(key, []);
  byDate.get(key).push(ev);
}
// Same cleanup as Parasha.cleanTitle: no parentheses, no trailing year digits.
const clean = s => s.replace(/[()]/g, '').replace(/[\d ]+$/, '');
const titles = new Set();
for (const [, evs] of byDate) {
  const d = evs[0].getDate().greg();
  if (d.getDay() !== 6) continue;
  const parsha = evs.find(e => e.getFlags() & flags.PARSHA_HASHAVUA);
  if (parsha) {
    titles.add(clean(parsha.render('he-x-NoNikud')));
    continue;
  }
  for (const e of evs) {
    if (e.getFlags() & (flags.MINOR_HOLIDAY | flags.EREV)) continue;
    titles.add(clean(e.render('he-x-NoNikud')));
  }
}
const list = [...titles].sort((a, b) => b.length - a.length);
writeFileSync(new URL('../face/test/TitleFixtures.mc', import.meta.url), `import Toybox.Lang;

// Generated by tools/titles-oracle.mjs from @hebcal/core — do not edit.
(:test)
module TitleFixtures {
    const TITLES = [
${list.map(t => `        "${t}"`).join(',\n')}
    ];
}
`);
console.log(`${list.length} titles; longest: ${list.slice(0, 4).join(' | ')}`);
