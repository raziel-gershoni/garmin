SIZE = 13
ADVANCE = 14


def write_png(path, width, height, rows, color_type):
    """rows: list of bytes, already in the PNG pixel format for color_type (0 = gray8, 2 = rgb8)."""
    raw = b"".join(b"\x00" + r for r in rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def icon_font(out_dir):
    glyphs = {ch: [line for line in art.strip("\n").splitlines()] for ch, art in ICONS.items()}
    width = ADVANCE * len(glyphs)
    pixels = [[0] * width for _ in range(SIZE)]
    lines = []
    for i, (ch, art) in enumerate(glyphs.items()):
        assert len(art) == SIZE and all(len(row) == SIZE for row in art), ch
        for y, row in enumerate(art):
            for x, c in enumerate(row):
                if c == "#":
                    pixels[y][i * ADVANCE + x] = 255  # white glyph on black
        lines.append(f"char id={ord(ch)} x={i * ADVANCE} y=0 width={SIZE} height={SIZE} "
                     f"xoffset=0 yoffset=0 xadvance={ADVANCE} page=0 chnl=15")
    write_png(out_dir / "icons.png", width, SIZE, [bytes(r) for r in pixels], 0)
    fnt = [
        f'info face="HebrewFaceIcons" size={SIZE} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={SIZE} base={SIZE} scaleW={width} scaleH={SIZE} pages=1 packed=0",
        'page id=0 file="icons.png"',
        f"chars count={len(lines)}",
        *lines,
    ]
    (out_dir / "icons.fnt").write_text("\n".join(fnt) + "\n")


def launcher_icon(path, crescent):
    """62x62: a ring with a crescent moon (face) or a filled disk with a crescent cut-out (glance)."""
    n, c = 62, 30.5
    rows = []
    for y in range(n):
        row = bytearray()
        for x in range(n):
            d = ((x - c) ** 2 + (y - c) ** 2) ** 0.5
            moon = d < 17 and ((x - c - 8) ** 2 + (y - c + 5) ** 2) ** 0.5 > 14
            if crescent:
                on = (27 <= d <= 30) or moon
            else:
                on = d <= 30 and not moon
            v = 255 if on else 0
            row += bytes((v, v, v))
        rows.append(bytes(row))
    write_png(path, n, n, rows, 2)


def band(path, width=176, height=49):
    """The date band's grey: a 50% checkerboard, the only grey a 1-bit screen can show."""
    rows = [bytes(255 if (x + y) % 2 == 0 else 0 for x in range(width)) for y in range(height)]
    write_png(path, width, height, rows, 0)


